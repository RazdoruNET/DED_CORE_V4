// Стоковая карта «на среднестатистический 250 см³»: семь точек, мягкие углы.
//
// Задача карты — завестись и поехать почти на любом одностволе 110…600 см³, а не выдать
// максимум: углы ниже отстроенных, детонации нет даже на плохом бензине. Дальше владелец
// правит её в разделе «Карты» приложения.
//
// Прошивка читает только те точки, что влезают в тип двигателя (type 0 — семь), остальные
// здесь повторяют последний угол: таблица остаётся целой при смене типа двигателя.
//
//   обороты: 1200, 1800, 2500, 3500, 5000, 7000, 9500   (rpmsArr_0, RPMs.h)
//   углы:      10,   15,   22,   27,   30,   32,   31
//
// Опорные точки для понимания: на холостых 1500 об/мин угол около 12°, середина 25…30°,
// полка 31…32° — это безопасный «сток», который заводится и киком, и стартером.

